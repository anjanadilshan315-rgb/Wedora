const test = require("node:test");
const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const path = require("node:path");
const fs = require("node:fs/promises");
const databasePath = path.join(process.cwd(), ".data", `premium-test-${randomUUID()}.db`);
process.env.FREE_DATABASE_URL = `file:${databasePath.replaceAll("\\", "/")}`;
process.env.FREE_ALLOW_LOCAL_DATABASE = "true";
const load = require("./load-typescript.cjs");
const studio = load("src/lib/server/premium-studio.ts");
const standard = load("src/lib/server/standard-studio.ts");
const { freeDatabase } = load("src/lib/server/free-database.ts");
const { PREMIUM_SAMPLE, AURELINE_SAMPLE, WALAWWA_SAMPLE, EVERMORE_SAMPLE } = load("src/lib/premium-invitation.ts");

test("Premium persists protected publication, owned uploads, 500+ guests, answers, seating, analytics and priority requests", async () => {
  await fs.mkdir(path.dirname(databasePath), { recursive: true });
  const db = await freeDatabase();
  const user = { id: randomUUID(), email: "premium-test@example.com" };
  const other = { id: randomUUID(), email: "other-premium@example.com" };
  try {
    for (const owner of [user, other]) await db.execute({ sql: "INSERT INTO studio_users(id,email,password_hash,created_at) VALUES (?,?,?,?)", args: [owner.id, owner.email, "unused", new Date().toISOString()] });
    const bytes = Buffer.from("ID3test-audio-upload");
    const upload = await studio.storeMedia(user, "audio/mpeg", bytes);
    assert.deepEqual((await studio.mediaFile(upload.url.split("/").pop(), user.id, () => undefined)).bytes, bytes);
    await assert.rejects(studio.storeMedia(user, "text/html", Buffer.from("<script>")), (e) => e.status === 415);
    await assert.rejects(studio.storeMedia(user, "audio/mpeg", Buffer.alloc(9 * 1024 * 1024)), (e) => e.status === 413);
    const details = { ...PREMIUM_SAMPLE, weddingDate: "2099-10-09", rsvpDeadline: "2099-09-25", passwordEnabled: true, musicUrl: upload.url, questions: [{ id: "meal", label: "Meal choice", type: "select", required: true, options: ["Vegan", "Fish"] }], seatingTables: [{ id: "rose", name: "Rose Table", capacity: 2 }] };
    await assert.rejects(studio.saveDraft(user, details), (e) => e.status === 400);
    await assert.rejects(studio.saveDraft(user, { ...details, musicUrl: "", videoUrl: upload.url }, "a-private-invitation"), (e) => e.status === 400);
    const saved = await studio.saveDraft(user, details, "a-private-invitation");
    const slug = saved.invitation.slug;
    assert.match(slug, /^[a-f0-9]{24}$/);
    assert.equal((await standard.snapshot(user)).invitation, null);
    await assert.rejects(studio.saveDraft(other, details, "a-private-invitation"), (e) => e.status === 400);
    await assert.rejects(studio.publicInvitation(slug), (e) => e.status === 404);
    await assert.rejects(studio.publishInvitation(user, 0, true), (e) => e.status === 409);
    await studio.publishInvitation(user, saved.invitation.version, true);
    await assert.rejects(studio.publicInvitation(slug), (e) => e.status === 423);
    await assert.rejects(studio.mediaFile(upload.url.split("/").pop(), undefined, () => undefined), (e) => e.status === 423);
    await assert.rejects(studio.unlockInvitation(slug, "wrong"), (e) => e.status === 401);
    const access = await studio.unlockInvitation(slug, "a-private-invitation");
    const unlocked = await studio.publicInvitation(slug, undefined, access, true);
    assert.deepEqual(unlocked.details.seatingTables, []);
    assert.ok(!JSON.stringify(unlocked).includes("password_hash"));
    assert.deepEqual((await studio.mediaFile(upload.url.split("/").pop(), undefined, () => access)).bytes, bytes);
    const guest = (await studio.addGuest(user, { name: "Charlotte" })).guests[0];
    await studio.updateGuest(user, { token: guest.token, tableId: "rose", group: "Family", notes: "Private note" });
    const input = { attending: true, headCount: 2, events: ["wedding", "homecoming"], dietary: "No nuts", message: "Lovely", answers: { meal: "Vegan" } };
    await assert.rejects(studio.replyToInvitation(slug, { ...input, answers: {} }, guest.token, access), (e) => e.status === 400);
    await studio.replyToInvitation(slug, input, guest.token, access);
    const result = await studio.publicInvitation(slug, guest.token, access, true);
    assert.equal(result.guest.table, "Rose Table"); assert.equal(result.guest.reply.answers.meal, "Vegan");
    assert.ok(!JSON.stringify(result).includes("Private note"));
    await assert.rejects(studio.replyToInvitation(slug, { ...input, headCount: 3 }, guest.token, access), (e) => e.status === 409);
    const next = (await studio.addGuest(user, { name: "No seats left" })).guests.find((g) => g.name === "No seats left");
    await assert.rejects(studio.updateGuest(user, { token: next.token, tableId: "rose" }), (e) => e.status === 409);
    await assert.rejects(studio.updateGuest(other, { token: guest.token, tableId: "rose" }), (e) => e.status === 404);
    await assert.rejects(studio.saveDraft(user, { ...details, seatingTables: [] }), (e) => e.status === 409);
    // Two concurrent assignments cannot reserve the same final seat.
    details.seatingTables.push({ id: "peony", name: "Peony", capacity: 1 });
    await studio.saveDraft(user, details);
    await studio.addGuest(user, { name: "Race A" });
    const racers = (await studio.addGuest(user, { name: "Race B" })).guests.filter((g) => g.name.startsWith("Race "));
    const assignments = await Promise.allSettled(racers.map((g) => studio.updateGuest(user, { token: g.token, tableId: "peony" })));
    assert.equal(assignments.filter((r) => r.status === "fulfilled").length, 1);
    assert.equal(assignments.filter((r) => r.status === "rejected" && r.reason.status === 409).length, 1);
    // Premium has no Standard 500-guest quota.
    await db.batch(Array.from({ length: 510 }, (_, i) => ({ sql: "INSERT INTO premium_guests(token,invitation_id,name,name_key) VALUES (?,?,?,?)", args: [randomUUID(), saved.invitation.id, `Seed ${i}`, `seed ${i}`] })), "write");
    assert.ok((await studio.addGuest(user, { name: "Beyond 500" })).guests.length > 500);
    const changed = await studio.saveDraft(user, { ...details, greetingMessage: "Draft only" }, "changed-private-password");
    assert.notEqual((await studio.publicInvitation(slug, undefined, access)).details.greetingMessage, "Draft only");
    await studio.publishInvitation(user, changed.invitation.version, true);
    await assert.rejects(studio.publicInvitation(slug, undefined, access), (e) => e.status === 423);
    const newAccess = await studio.unlockInvitation(slug, "changed-private-password");
    assert.equal((await studio.publicInvitation(slug, undefined, newAccess)).details.greetingMessage, "Draft only");
    const support = await studio.supportRequest(user, "Please help with my wedding stationery.");
    assert.equal(support.tickets[0].status, "priority-queued"); assert.equal(support.invitation.views, 2);
    assert.equal(support.guests.find((g) => g.token === guest.token).visits, 1);
    await studio.publishInvitation(user, changed.invitation.version, false);
    await assert.rejects(studio.publicInvitation(slug, undefined, newAccess), (e) => e.status === 404);
    await assert.rejects(studio.mediaFile(upload.url.split("/").pop(), undefined, () => newAccess), (e) => e.status === 404);
    const aureline = await studio.saveDraft(other, { ...AURELINE_SAMPLE, weddingDate: "2099-12-12", rsvpDeadline: "2099-11-28" });
    await studio.publishInvitation(other, aureline.invitation.version, true);
    const aurelineGuest = (await studio.addGuest(other, { name: "Aureline guest" })).guests[0];
    await studio.updateGuest(other, { token: aurelineGuest.token, tableId: "rose" });
    await studio.replyToInvitation(aureline.invitation.slug, { attending: true, headCount: 3, events: ["wedding", "homecoming"], dietary: "Vegetarian", message: "Lovely journey", answers: { song: "Our favourite song" } }, aurelineGuest.token);
    const liveAureline = await studio.publicInvitation(aureline.invitation.slug, aurelineGuest.token);
    assert.equal(liveAureline.details.premiumTemplate, "aureline");
    assert.equal(liveAureline.details.opening, "journey");
    assert.equal(liveAureline.guest.reply.headCount, 3); assert.equal(liveAureline.guest.table, "The Rose Table");
    const heritageUser = { id: randomUUID(), email: "walawwa-test@example.com" };
    await db.execute({ sql: "INSERT INTO studio_users(id,email,password_hash,created_at) VALUES (?,?,?,?)", args: [heritageUser.id, heritageUser.email, "unused", new Date().toISOString()] });
    const heritage = await studio.saveDraft(heritageUser, { ...WALAWWA_SAMPLE, weddingDate: "2099-08-21", rsvpDeadline: "2099-08-01", passwordEnabled: true }, "heritage-private-password");
    await studio.publishInvitation(heritageUser, heritage.invitation.version, true);
    await assert.rejects(studio.publicInvitation(heritage.invitation.slug), e => e.status === 423);
    const heritageAccess = await studio.unlockInvitation(heritage.invitation.slug, "heritage-private-password");
    const heritageGuest = (await studio.addGuest(heritageUser, { name: "Heritage guest" })).guests[0];
    await studio.updateGuest(heritageUser, { token: heritageGuest.token, tableId: "jasmine" });
    await studio.replyToInvitation(heritage.invitation.slug, { attending: true, headCount: 2, events: ["wedding", "reception"], dietary: "Vegetarian", message: "See you beneath the lanterns", answers: { song: "Our wedding song" } }, heritageGuest.token, heritageAccess);
    const liveHeritage = await studio.publicInvitation(heritage.invitation.slug, heritageGuest.token, heritageAccess, true);
    assert.equal(liveHeritage.details.premiumTemplate, "walawwa"); assert.equal(liveHeritage.details.opening, "doors");
    assert.equal(liveHeritage.guest.table, "The Jasmine Table"); assert.equal(liveHeritage.guest.reply.headCount, 2);
    assert.equal(liveHeritage.guest.reply.answers.song, "Our wedding song");
    assert.equal((await studio.snapshot(heritageUser)).guests[0].visits, 1);
    const filmUser = { id: randomUUID(), email: "evermore-test@example.com" };
    await db.execute({ sql: "INSERT INTO studio_users(id,email,password_hash,created_at) VALUES (?,?,?,?)", args: [filmUser.id, filmUser.email, "unused", new Date().toISOString()] });
    const filmDraft = await studio.saveDraft(filmUser, { ...EVERMORE_SAMPLE, weddingDate: "2099-05-20", rsvpDeadline: "2099-05-06" });
    await studio.publishInvitation(filmUser, filmDraft.invitation.version, true);
    const filmGuest = (await studio.addGuest(filmUser, { name: "Film guest" })).guests[0];
    await studio.updateGuest(filmUser, { token: filmGuest.token, tableId: "wisteria" });
    await studio.replyToInvitation(filmDraft.invitation.slug, { attending: true, headCount: 2, events: ["wedding", "poruwa"], dietary: "No nuts", message: "Our best wishes for your new chapter", answers: { song: "Our song" } }, filmGuest.token);
    const liveFilm = await studio.publicInvitation(filmDraft.invitation.slug, filmGuest.token, undefined, true);
    assert.equal(liveFilm.details.premiumTemplate, "evermore"); assert.equal(liveFilm.details.opening, "film");
    assert.equal(liveFilm.guest.table, "The Wisteria Table"); assert.equal(liveFilm.guest.reply.message, "Our best wishes for your new chapter");
    assert.equal(liveFilm.guest.reply.events.length, 2);
    assert.equal((await studio.snapshot(user)).invitation.details.premiumTemplate, "rose");
  } finally {
    db.close();
    for (const suffix of ["", "-wal", "-shm"]) await fs.rm(databasePath + suffix, { force: true }).catch((e) => { if (e.code !== "EBUSY") throw e; });
  }
});
